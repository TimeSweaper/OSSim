#include "db_manager.hpp"

#include <cstdlib>
#include <iostream>

using namespace std;
using namespace oracle::occi;

// Create the Oracle environment once when the manager is constructed.
DatabaseManager::DatabaseManager() {
    try {
        env = Environment::createEnvironment(Environment::DEFAULT);
    } catch (const SQLException& error) {
        cerr << "[Fatal Error] Oracle setup failed: " << error.getMessage() << '\n';
        exit(EXIT_FAILURE);
    }
}

// Close the connection and release the environment when the manager is destroyed.
DatabaseManager::~DatabaseManager() {
    try {
        if (conn != nullptr) {
            env->terminateConnection(conn);
        }
        if (env != nullptr) {
            Environment::terminateEnvironment(env);
        }
    } catch (const SQLException& error) {
        cerr << "[Cleanup Error] " << error.getMessage() << '\n';
    }
}

bool DatabaseManager::connect(const DBConfig& cfg) {
    try {
        if (conn != nullptr) {
            env->terminateConnection(conn);
            conn = nullptr;
        }
        conn = env->createConnection(cfg.user, cfg.password, cfg.connect_string);
        conn->setAutoCommit(true);
        cout << "[DB Connected] Successfully connected to Oracle.\n";
        return true;
    } catch (const SQLException& error) {
        cerr << "[Connection Failed] " << error.getMessage() << '\n';
        return false;
    }
}

void DatabaseManager::executeQuery(const string& query) {
    if (conn == nullptr) {
        cerr << "[SQL Error] No Oracle connection is available.\n";
        return;
    }

    Statement* statement = nullptr;
    try {
        statement = conn->createStatement(query);
        statement->executeUpdate();
        conn->terminateStatement(statement);
    } catch (const SQLException& error) {
        if (statement != nullptr) {
            try {
                conn->terminateStatement(statement);
            } catch (const SQLException&) {
                // Preserve and report the original SQL error.
            }
        }
        if (error.getErrorCode() != 955) {
            cerr << "[SQL Error] " << error.getMessage() << '\n';
        }
    }
}

void DatabaseManager::initSchema() {
    // Oracle reports error 955 when a table already exists; executeQuery ignores it.
    executeQuery("CREATE TABLE experiments ("
                 "id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
                 "name VARCHAR2(100) DEFAULT 'SmartOS Simulation', "
                 "experiment_type VARCHAR2(50) NOT NULL, "
                 "algorithm VARCHAR2(50) NOT NULL, "
                 "time_quantum NUMBER DEFAULT NULL, "
                 "workload_type VARCHAR2(50) DEFAULT 'N/A', "
                 "created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP)");

    executeQuery("CREATE TABLE processes ("
                 "id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
                 "experiment_id NUMBER NOT NULL, pid NUMBER NOT NULL, "
                 "arrival_time NUMBER DEFAULT 0, cpu_burst_time NUMBER NOT NULL, "
                 "completion_time NUMBER DEFAULT 0, turnaround_time NUMBER DEFAULT 0, "
                 "waiting_time NUMBER DEFAULT 0, "
                 "CONSTRAINT fk_process_exp FOREIGN KEY (experiment_id) "
                 "REFERENCES experiments(id) ON DELETE CASCADE)");

    executeQuery("CREATE TABLE process_events ("
                 "id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
                 "experiment_id NUMBER NOT NULL, pid NUMBER NOT NULL, "
                 "start_tick NUMBER NOT NULL, end_tick NUMBER NOT NULL, "
                 "state VARCHAR2(50) NOT NULL, details VARCHAR2(255), "
                 "CONSTRAINT fk_event_exp FOREIGN KEY (experiment_id) "
                 "REFERENCES experiments(id) ON DELETE CASCADE)");

    executeQuery("CREATE TABLE scheduling_results ("
                 "id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
                 "experiment_id NUMBER NOT NULL UNIQUE, "
                 "avg_waiting_time FLOAT NOT NULL, avg_turnaround_time FLOAT NOT NULL, "
                 "total_execution_ticks NUMBER NOT NULL, "
                 "CONSTRAINT fk_result_exp FOREIGN KEY (experiment_id) "
                 "REFERENCES experiments(id) ON DELETE CASCADE)");
}

int DatabaseManager::createExperiment(const string& type,
                                     const string& algo,
                                     int quantum,
                                     const string& workload_type) {
    if (conn == nullptr) {
        cerr << "[Insert Error] No Oracle connection is available.\n";
        return -1;
    }

    Statement* statement = nullptr;
    try {
        // Bind values separately so quotes in user data cannot alter the SQL command.
        statement = conn->createStatement(
            "INSERT INTO experiments (experiment_type, algorithm, time_quantum, workload_type) "
            "VALUES (:1, :2, :3, :4) RETURNING id INTO :5");
        statement->setString(1, type);
        statement->setString(2, algo);
        if (quantum > 0) {
            statement->setInt(3, quantum);
        } else {
            statement->setNull(3, Type::OCCIINT);
        }
        statement->setString(4, workload_type);
        statement->registerOutParam(5, Type::OCCIINT);
        statement->executeUpdate();
        // RETURNING gives this insert's ID directly, even if another client inserts too.
        const int experiment_id = statement->getInt(5);
        conn->terminateStatement(statement);
        return experiment_id;
    } catch (const SQLException& error) {
        if (statement != nullptr) {
            try {
                conn->terminateStatement(statement);
            } catch (const SQLException&) {
                // Preserve and report the original insert error.
            }
        }
        cerr << "[Insert Error] " << error.getMessage() << '\n';
        return -1;
    }
}

void DatabaseManager::insertProcess(int exp_id, const Process& process) {
    if (conn == nullptr) {
        cerr << "[Insert Error] No Oracle connection is available.\n";
        return;
    }
    Statement* statement = nullptr;
    try {
        statement = conn->createStatement(
            "INSERT INTO processes (experiment_id, pid, arrival_time, cpu_burst_time, "
            "completion_time, turnaround_time, waiting_time) "
            "VALUES (:1, :2, :3, :4, :5, :6, :7)");
        statement->setInt(1, exp_id);
        statement->setInt(2, process.pid);
        statement->setInt(3, process.arrival_time);
        statement->setInt(4, process.cpu_burst_time);
        statement->setInt(5, process.completion_time);
        statement->setInt(6, process.turnaround_time);
        statement->setInt(7, process.waiting_time);
        statement->executeUpdate();
        conn->terminateStatement(statement);
    } catch (const SQLException& error) {
        if (statement != nullptr) {
            try { conn->terminateStatement(statement); } catch (const SQLException&) {}
        }
        cerr << "[Insert Error] " << error.getMessage() << '\n';
    }
}

